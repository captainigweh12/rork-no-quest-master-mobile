type TranslationKey = keyof typeof translations.en;
type NestedTranslationKey<T> = T extends object
  ? { [K in keyof T]: T[K] extends object ? `${K & string}.${NestedTranslationKey<T[K]> & string}` : K & string }[keyof T]
  : never;

export type SupportedLanguage = keyof typeof translations;

export function getTranslations(lang: string = 'en') {
  const language = (translations[lang as SupportedLanguage] ? lang : 'en') as SupportedLanguage;
  return translations[language];
}

export function translate(lang: string = 'en', path: string, fallback?: string): string {
  const language = (translations[lang as SupportedLanguage] ? lang : 'en') as SupportedLanguage;
  const keys = path.split('.');
  let value: any = translations[language];

  for (const key of keys) {
    if (value && typeof value === 'object' && key in value) {
      value = value[key];
    } else {
      return fallback || path;
    }
  }

  return typeof value === 'string' ? value : fallback || path;
}
